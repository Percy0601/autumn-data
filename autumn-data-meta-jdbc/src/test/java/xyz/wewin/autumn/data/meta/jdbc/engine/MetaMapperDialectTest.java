import static org.assertj.core.api.Assertions.assertThat;

/**
 * 同一套动态层在 MySQL 与 PostgreSQL 两种方言下跑通：建表语法、标识符引用、分页写法各按方言来，
 * 生成实体、Mapper 语句、结果映射、CRUD 的结果完全一致。
 *
 * <p>本机没有 MySQL / PostgreSQL 服务时，用 H2 的 {@code MODE=MySQL} / {@code MODE=PostgreSQL}
 * 起同构的库，方言类仍分别用 {@link MySqlDialect} / {@link PostgreSqlDialect}，
 * 验证的是「方言产出的 SQL 能在这两种语法环境里执行」，而不是 H2 自己的方言。</p>
 */
class MetaMapperDialectTest {

	private static final AtomicInteger DB_SEQ = new AtomicInteger();

	@TempDir
	Path mapperDirectory;

	@Test
	void mySqlDialectRunsCrudMapperAndPaging() throws Exception {
		run("MODE=MySQL;DATABASE_TO_LOWER=TRUE", new MySqlDialect(),
				"CREATE TABLE dialect_order (id BIGINT AUTO_INCREMENT PRIMARY KEY, "
						+ "order_no VARCHAR(32) NOT NULL, amount DECIMAL(12,2), status INT, "
						+ "deleted_flag INT NOT NULL DEFAULT 0)");
	}

	@Test
	void postgreSqlDialectRunsCrudMapperAndPaging() throws Exception {
		run("MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE", new PostgreSqlDialect(),
				"CREATE TABLE dialect_order (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
						+ "order_no VARCHAR(32) NOT NULL, amount DECIMAL(12,2), status INT, "
						+ "deleted_flag INT NOT NULL DEFAULT 0)");
	}

	private void run(String mode, Dialect dialect, String ddl) throws Exception {
		JdbcDataSource dataSource = new JdbcDataSource();
		dataSource.setURL("jdbc:h2:mem:dialect_" + DB_SEQ.incrementAndGet() + ";" + mode + ";DB_CLOSE_DELAY=-1");
		dataSource.setUser("sa");
		try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement()) {
			statement.execute(ddl);
		}

		JdbcConnectionSource connections = new JdbcConnectionSource(dataSource);
		AutumnJdbc jdbc = new AutumnJdbc(connections, dialect, FetchPolicy.defaults());
		MetaTableRegistry registry = new MetaTableRegistry(dataSource, dialect, Set.of("deleted_flag"));
		MetaStatementStore statements = new MetaStatementStore(this.mapperDirectory, true, dialect);
		MetaMapperClient client = new MetaMapperClient("test", jdbc, connections, registry,
				new MetaSqlBuilder(dialect), statements, new MetaEntityRegistry(), new MetaPlanCache(), 1000);

		MetaClass first = client.save(row(client, "order_no", "D001", "amount", "10.00", "status", 1));
		client.save(row(client, "order_no", "D002", "amount", "20.00", "status", 1));
		assertThat(first.get("id")).isInstanceOf(Number.class);

		MetaClass loaded = client.findById("dialect_order", first.get("id")).orElseThrow();
		assertThat(loaded.getString("order_no")).isEqualTo("D001");
		assertThat(loaded.getBigDecimal("amount")).isEqualByComparingTo("10.00");

		loaded.set("status", 2);
		assertThat(client.update(loaded)).isEqualTo(1);
		assertThat(client.findById("dialect_order", first.get("id")).orElseThrow().getInt("status")).isEqualTo(2);

		assertThat(client.findList("dialect_order", MetaQuery.by("status", 1)))
				.extracting(row -> row.getString("order_no")).containsExactly("D002");
		Page<MetaClass> page = client.findPage("dialect_order", MetaQuery.all(), Pageable.of(0, 1));
		assertThat(page.total()).isEqualTo(2);
		assertThat(page.content()).hasSize(1);

		// 命名语句：第一次访问按表结构生成 Mapper XML，SQL 用当前方言的引号与 LIMIT
		assertThat(client.selectCount("dialect_order", "selectCount", params())).isEqualTo(2);
		assertThat(client.selectList("dialect_order", "selectList", params("status", 1)))
				.extracting(row -> row.getString("order_no")).containsExactly("D002");
		assertThat(client.sqlFor("dialect_order", "selectList", params("status", 1)).sql())
				.contains(dialect.quoteIdentifier("order_no"))
				.contains("FROM " + dialect.quoteIdentifier("dialect_order"));
	}

	private static MetaClass row(MetaMapperClient client, Object... nameValues) {
		MetaClass entity = client.newEntity("dialect_order");
		for (int i = 0; i < nameValues.length; i += 2) {
			entity.set((String) nameValues[i], nameValues[i + 1]);
		}
		return entity;
	}

	private static MetaClass params(Object... nameValues) {
		MetaClass entity = new MetaClass();
		for (int i = 0; i < nameValues.length; i += 2) {
			entity.set((String) nameValues[i], nameValues[i + 1]);
		}
		return entity;
	}

}
